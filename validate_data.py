"""
validate_data.py

This script validates the healthcare CSV files generated by
generate_sample_data.py.

Files checked:
    - patients.csv
    - providers.csv
    - appointments.csv
    - payments.csv

Validation checks:
    1. Required columns
    2. Null primary keys
    3. Duplicate IDs
    4. Invalid appointment statuses
    5. Negative payment amounts
    6. Appointment referencing nonexistent patient
    7. Payment referencing nonexistent appointment
    8. Invalid dates
    9. Billed/paid/outstanding inconsistencies

The raw data is NOT modified.

A validation report is generated in:
    data/processed/validation_report.csv
"""

from pathlib import Path

import pandas as pd


# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path(__file__).resolve().parent

RAW_DIR = BASE_DIR / "data" / "raw"

PROCESSED_DIR = BASE_DIR / "data" / "processed"

VALIDATION_REPORT = (
    PROCESSED_DIR / "validation_report.csv"
)


