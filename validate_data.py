# ============================================================
# PRIMARY KEYS
# ============================================================

PRIMARY_KEYS = {

    "patients.csv": "patient_id",

    "providers.csv": "provider_id",

    "appointments.csv": "appointment_id",

    "payments.csv": "payment_id",
}


# ============================================================
# VALID APPOINTMENT STATUSES
# ============================================================

VALID_APPOINTMENT_STATUSES = {
    "Completed",
    "Scheduled",
    "Cancelled",
    "No Show",
}


# ============================================================
# VALID PAYMENT STATUSES
# ============================================================

VALID_PAYMENT_STATUSES = {
    "Paid",
    "Pending",
    "Failed",
}


# ============================================================
# STORE VALIDATION ERRORS
# ============================================================

validation_errors = []


def add_error(
    file_name,
    check_name,
    row_number,
    column_name,
    value,
    message,
):
    """
    Add one validation error to the report.
    """

    validation_errors.append(
        {
            "file": file_name,
            "check": check_name,
            "row": row_number,
            "column": column_name,
            "value": value,
            "message": message,
        }
    )


# ============================================================
# LOAD DATA
# ============================================================

def load_data():

    print("=" * 70)
    print("LOADING DATA")
    print("=" * 70)

    data = {}

    files = [
        "patients.csv",
        "providers.csv",
        "appointments.csv",
        "payments.csv",
    ]

    for file_name in files:

        file_path = RAW_DIR / file_name

        if not file_path.exists():

            print(
                f"ERROR: {file_name} not found at {file_path}"
            )

            continue

        try:

            df = pd.read_csv(file_path)

            data[file_name] = df

            print(
                f"{file_name}: {len(df)} records loaded"
            )

        except Exception as error:

            print(
                f"ERROR reading {file_name}: {error}"
            )

    print()

    return data


# ============================================================
# CHECK 1: REQUIRED COLUMNS
# ============================================================

def check_required_columns(data):

    print("Checking required columns...")

    for file_name, required_columns in REQUIRED_COLUMNS.items():

        if file_name not in data:
            continue

        df = data[file_name]

        actual_columns = set(df.columns)

        for column in required_columns:

            if column not in actual_columns:

                add_error(
                    file_name=file_name,
                    check_name="required_columns",
                    row_number="N/A",
                    column_name=column,
                    value="MISSING",
                    message=(
                        f"Required column '{column}' "
                        f"is missing."
                    ),
                )

                print(
                    f"  ERROR: {file_name} -> "
                    f"missing column '{column}'"
                )

    print()


# ============================================================
# CHECK 2: NULL PRIMARY KEYS
# ============================================================

def check_null_primary_keys(data):

    print("Checking null primary keys...")

    for file_name, primary_key in PRIMARY_KEYS.items():

        if file_name not in data:
            continue

        df = data[file_name]

        if primary_key not in df.columns:
            continue

        null_rows = df[
            df[primary_key].isna()
            | (df[primary_key].astype(str).str.strip() == "")
        ]

        for index, row in null_rows.iterrows():

            add_error(
                file_name=file_name,
                check_name="null_primary_key",
                row_number=index + 2,
                column_name=primary_key,
                value="NULL",
                message=(
                    f"Primary key '{primary_key}' "
                    f"cannot be null."
                ),
            )

        if len(null_rows) > 0:

            print(
                f"  ERROR: {file_name} -> "
                f"{len(null_rows)} null primary keys"
            )

    print()


# ============================================================
# CHECK 3: DUPLICATE IDS
# ============================================================

def check_duplicate_ids(data):

    print("Checking duplicate IDs...")

    for file_name, primary_key in PRIMARY_KEYS.items():

        if file_name not in data:
            continue

        df = data[file_name]

        if primary_key not in df.columns:
            continue

        duplicate_mask = (
            df[primary_key].duplicated(
                keep=False
            )
            & df[primary_key].notna()
        )

        duplicate_rows = df[duplicate_mask]

        for index, row in duplicate_rows.iterrows():

            duplicate_value = row[primary_key]

            add_error(
                file_name=file_name,
                check_name="duplicate_id",
                row_number=index + 2,
                column_name=primary_key,
                value=duplicate_value,
                message=(
                    f"Duplicate ID found: "
                    f"{duplicate_value}"
                ),
            )

        if len(duplicate_rows) > 0:

            print(
                f"  ERROR: {file_name} -> "
                f"{len(duplicate_rows)} rows "
                f"with duplicate IDs"
            )

    print()


# ============================================================
# CHECK 4: INVALID APPOINTMENT STATUSES
# ============================================================

def check_appointment_statuses(data):

    print("Checking appointment statuses...")

    file_name = "appointments.csv"

    if file_name not in data:
        return

    df = data[file_name]

    if "appointment_status" not in df.columns:
        return

    invalid_mask = ~df[
        "appointment_status"
    ].isin(VALID_APPOINTMENT_STATUSES)

    invalid_rows = df[invalid_mask]

    for index, row in invalid_rows.iterrows():

        status = row["appointment_status"]

        add_error(
            file_name=file_name,
            check_name="invalid_appointment_status",
            row_number=index + 2,
            column_name="appointment_status",
            value=status,
            message=(
                f"Invalid appointment status "
                f"'{status}'. "
                f"Allowed values: "
                f"{sorted(VALID_APPOINTMENT_STATUSES)}"
            ),
        )

    if len(invalid_rows) > 0:

        print(
            f"  ERROR: {len(invalid_rows)} "
            f"invalid appointment statuses"
        )

    print()


# ============================================================
# CHECK 5: NEGATIVE PAYMENT AMOUNTS
# ============================================================

def check_negative_payment_amounts(data):

    print("Checking negative payment amounts...")

    file_name = "payments.csv"

    if file_name not in data:
        return

    df = data[file_name]

    if "amount" not in df.columns:
        return

    numeric_amount = pd.to_numeric(
        df["amount"],
        errors="coerce"
    )

    negative_rows = df[
        numeric_amount < 0
    ]

    for index, row in negative_rows.iterrows():

        amount = row["amount"]

        add_error(
            file_name=file_name,
            check_name="negative_payment_amount",
            row_number=index + 2,
            column_name="amount",
            value=amount,
            message=(
                "Payment amount cannot be negative."
            ),
        )

    if len(negative_rows) > 0:

        print(
            f"  ERROR: {len(negative_rows)} "
            f"negative payment amounts"
        )

    print()


