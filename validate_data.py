# CHECK 8: INVALID DATES
# ============================================================

def check_invalid_dates(data):

    print("Checking invalid dates...")

    date_columns = {

        "patients.csv": [
            "date_of_birth",
            "registration_date",
        ],

        "providers.csv": [],

        "appointments.csv": [
            "appointment_date",
            "created_at",
        ],

        "payments.csv": [
            "payment_date",
        ],
    }

    for file_name, columns in date_columns.items():

        if file_name not in data:
            continue

        df = data[file_name]

        for column in columns:

            if column not in df.columns:
                continue

            converted_dates = pd.to_datetime(
                df[column],
                errors="coerce"
            )

            invalid_mask = (
                converted_dates.isna()
                & df[column].notna()
                & (
                    df[column]
                    .astype(str)
                    .str.strip()
                    != ""
                )
            )

            invalid_rows = df[invalid_mask]

            for index, row in invalid_rows.iterrows():

                value = row[column]

                add_error(
                    file_name=file_name,
                    check_name="invalid_date",
                    row_number=index + 2,
                    column_name=column,
                    value=value,
                    message=(
                        f"Invalid date value "
                        f"'{value}'."
                    ),
                )

            if len(invalid_rows) > 0:

                print(
                    f"  ERROR: {file_name} -> "
                    f"{column}: "
                    f"{len(invalid_rows)} invalid dates"
                )

    print()


