# CHECK 6: APPOINTMENT -> PATIENT
# ============================================================

def check_appointment_patient_reference(data):

    print(
        "Checking appointment patient references..."
    )

    if "appointments.csv" not in data:
        return

    if "patients.csv" not in data:
        return

    appointments = data["appointments.csv"]

    patients = data["patients.csv"]

    if "patient_id" not in appointments.columns:
        return

    if "patient_id" not in patients.columns:
        return

    valid_patient_ids = set(
        patients["patient_id"]
        .dropna()
        .astype(str)
    )

    for index, row in appointments.iterrows():

        patient_id = str(
            row["patient_id"]
        )

        if patient_id not in valid_patient_ids:

            add_error(
                file_name="appointments.csv",
                check_name="invalid_patient_reference",
                row_number=index + 2,
                column_name="patient_id",
                value=patient_id,
                message=(
                    f"Appointment references "
                    f"nonexistent patient "
                    f"'{patient_id}'."
                ),
            )

    invalid_count = sum(
        1
        for error in validation_errors
        if error["check"]
        == "invalid_patient_reference"
    )

    if invalid_count > 0:

        print(
            f"  ERROR: {invalid_count} "
            f"appointments reference "
            f"nonexistent patients"
        )

    print()


