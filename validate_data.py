# CHECK 9: BILLED / PAID / OUTSTANDING
# ============================================================

def check_billed_paid_outstanding(data):

    print(
        "Checking billed/paid/outstanding "
        "consistency..."
    )

    if "payments.csv" not in data:
        return

    payments = data["payments.csv"]

    required_columns = [
        "amount",
        "insurance_amount",
        "patient_amount",
        "payment_status",
    ]

    for column in required_columns:

        if column not in payments.columns:

            print(
                f"  WARNING: '{column}' column "
                f"not found in payments.csv"
            )

            return

    # Convert monetary columns to numbers
    amount = pd.to_numeric(
        payments["amount"],
        errors="coerce"
    )

    insurance_amount = pd.to_numeric(
        payments["insurance_amount"],
        errors="coerce"
    )

    patient_amount = pd.to_numeric(
        payments["patient_amount"],
        errors="coerce"
    )

    # --------------------------------------------------------
    # Check 9A:
    #
    # Billed amount should equal:
    #
    # insurance amount + patient amount
    #
    # Example:
    #
    # amount = 1500
    # insurance = 1200
    # patient = 300
    #
    # 1200 + 300 = 1500
    # --------------------------------------------------------

    calculated_total = (
        insurance_amount + patient_amount
    )

    inconsistent_split = (
        (amount - calculated_total).abs()
        > 0.01
    )

    for index in payments[
        inconsistent_split
    ].index:

        add_error(
            file_name="payments.csv",
            check_name="billed_paid_outstanding",
            row_number=index + 2,
            column_name="amount",
            value=amount.loc[index],
            message=(
                "Amount is inconsistent with "
                "insurance_amount + patient_amount."
            ),
        )

    # --------------------------------------------------------
    # Check 9B:
    #
    # Paid status should have a fully allocated amount.
    #
    # For Paid:
    #
    # insurance + patient = amount
    # outstanding = 0
    #
    # For Pending/Failed:
    # payment may not be fully paid.
    # --------------------------------------------------------

    paid_mask = (
        payments["payment_status"] == "Paid"
    )

    invalid_paid_rows = payments[
        paid_mask
        & (
            (amount - calculated_total).abs()
            > 0.01
        )
    ]

    for index in invalid_paid_rows.index:

        add_error(
            file_name="payments.csv",
            check_name="paid_amount_inconsistency",
            row_number=index + 2,
            column_name="payment_status",
            value="Paid",
            message=(
                "Payment is marked as Paid but "
                "billed amount does not match "
                "the allocated paid amounts."
            ),
        )

    # --------------------------------------------------------
    # Check 9C:
    #
    # Negative insurance/patient amounts
    # --------------------------------------------------------

    negative_insurance = payments[
        insurance_amount < 0
    ]

    for index in negative_insurance.index:

        add_error(
            file_name="payments.csv",
            check_name="negative_insurance_amount",
            row_number=index + 2,
            column_name="insurance_amount",
            value=insurance_amount.loc[index],
            message=(
                "Insurance amount cannot be negative."
            ),
        )

    negative_patient = payments[
        patient_amount < 0
    ]

    for index in negative_patient.index:

        add_error(
            file_name="payments.csv",
            check_name="negative_patient_amount",
            row_number=index + 2,
            column_name="patient_amount",
            value=patient_amount.loc[index],
            message=(
                "Patient amount cannot be negative."
            ),
        )

    # --------------------------------------------------------
    # Check 9D:
    #
    # Calculate outstanding amount.
    #
    # billed amount = amount
    #
    # paid amount =
    #     amount when payment is Paid
    #     0 otherwise
    #
    # outstanding =
    #     billed - paid
    #
    # This is calculated because the current
    # payments.csv schema does not contain a separate
    # outstanding_amount column.
    # --------------------------------------------------------

    calculated_paid = amount.where(
        payments["payment_status"] == "Paid",
        0
    )

    calculated_outstanding = (
        amount - calculated_paid
    )

    # Outstanding cannot be negative
    negative_outstanding = (
        calculated_outstanding < -0.01
    )

    for index in payments[
        negative_outstanding
    ].index:

        add_error(
            file_name="payments.csv",
            check_name="outstanding_amount",
            row_number=index + 2,
            column_name="amount",
            value=amount.loc[index],
            message=(
                "Outstanding amount cannot "
                "be negative."
            ),
        )

    total_errors = sum(
        1
        for error in validation_errors
        if error["check"]
        in {
            "billed_paid_outstanding",
            "paid_amount_inconsistency",
            "negative_insurance_amount",
            "negative_patient_amount",
            "outstanding_amount",
        }
    )

    if total_errors > 0:

        print(
            f"  ERROR: {total_errors} "
            f"financial inconsistencies found"
        )

    else:

        print(
            "  PASS: Billed/paid/outstanding "
            "amounts are consistent."
        )

    print()


# ============================================================
# GENERATE VALIDATION REPORT
# ============================================================

def generate_report():

    PROCESSED_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    if validation_errors:

        report_df = pd.DataFrame(
            validation_errors
        )

    else:

        report_df = pd.DataFrame(
            columns=[
                "file",
                "check",
                "row",
                "column",
                "value",
                "message",
            ]
        )

    report_df.to_csv(
        VALIDATION_REPORT,
        index=False
    )

    return report_df


# ============================================================
# PRINT SUMMARY
# ============================================================

def print_summary():

    print("=" * 70)
    print("VALIDATION SUMMARY")
    print("=" * 70)

    if not validation_errors:

        print("STATUS: PASS")
        print("No data quality errors found.")

    else:

        print("STATUS: FAIL")

        print(
            f"Total validation errors: "
            f"{len(validation_errors)}"
        )

        print()

        error_counts = {}

        for error in validation_errors:

            check = error["check"]

            error_counts[check] = (
                error_counts.get(check, 0) + 1
            )

        print("Errors by check:")

        for check, count in error_counts.items():

            print(
                f"  {check}: {count}"
            )

    print()

    print(
        f"Validation report: "
        f"{VALIDATION_REPORT}"
    )

    print("=" * 70)


# ============================================================
# MAIN
# ============================================================

def main():

    print()
    print("=" * 70)
    print("HEALTHCARE DATA VALIDATION")
    print("=" * 70)
    print()

    # Load CSV files
    data = load_data()

    if not data:

        print(
            "ERROR: No input files were found."
        )

        return

    # --------------------------------------------------------
    # Run validation checks
    # --------------------------------------------------------

    check_required_columns(data)

    check_null_primary_keys(data)

    check_duplicate_ids(data)

    check_appointment_statuses(data)

    check_negative_payment_amounts(data)

    check_appointment_patient_reference(data)

    check_payment_appointment_reference(data)

    check_invalid_dates(data)

    check_billed_paid_outstanding(data)

    # --------------------------------------------------------
    # Generate report
    # --------------------------------------------------------

    generate_report()

    # --------------------------------------------------------
    # Print final summary
    # --------------------------------------------------------

    print_summary()


# ============================================================
# PROGRAM ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()